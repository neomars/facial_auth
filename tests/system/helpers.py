def cut_inside_loaded_segments(data: bytes) -> bytes:
    """Truncate an ELF library so that its last loadable segment lies wholly beyond the end of
    the file: the dynamic loader then dies with SIGBUS when it touches those pages."""
    phoff, = struct.unpack_from("<Q", data, 0x20)
    phentsize, phnum = struct.unpack_from("<HH", data, 0x36)
    offsets = [struct.unpack_from("<IIQ", data, phoff + i * phentsize) for i in range(phnum)]
    last = max(off for kind, _flags, off in offsets if kind == 1)          # PT_LOAD
    return data[: (last & ~0xFFF) - 1]


# --------------------------------------------- driving a real sudo through a pty
COMMON_AUTH = Path("/etc/pam.d/common-auth")
AUTHENTICATED = "AUTHENTICATED-root"
WRONG = "definitely-not-the-password"
MARGIN = 2.0                      # slack on every time budget (slow CI machines)
CONNECT_TIMEOUT = 4.0             # pam_facial_auth: wait for the daemon's first reply
SLACK = 3.0                       # pam_facial_auth: slack added to the scan timeout
REPORT = []                       # rows for the human-readable table (FA_LOCKOUT_REPORT)



def reap(p):
    if not p.exited():
        with contextlib.suppress(ProcessLookupError):
            os.kill(p.pid, signal.SIGKILL)
        with contextlib.suppress(ChildProcessError):
            os.waitpid(p.pid, 0)
    with contextlib.suppress(OSError):
        os.close(p.fd)


def prompts(p):
    return p.buf.count("password for")


def wait_prompts(p, n, timeout):
    end = time.monotonic() + timeout
    while time.monotonic() < end and prompts(p) < n:
        p.pump(0.1)
    return prompts(p) >= n


def drive(name, *, budget, wrong_first=True, type_after=0.0,
          script="sudo -k; sudo sh -c 'echo AUTHENTICATED-$(id -un)'"):
    """One real `sudo`: wrong password first (must be refused), then the right one.

    `budget` is the longest acceptable wait before the password prompt shows up.
    """
    t0 = time.monotonic()
    p = Pty(sudo_cmd(script))
    try:
        assert p.expect("password for", budget + MARGIN), \
            f"[{name}] no password prompt within {budget + MARGIN:.1f}s: authentication is blocked\n{p.buf}"
        shown = time.monotonic() - t0
        assert AUTHENTICATED not in p.buf, f"[{name}] authenticated without any password\n{p.buf}"
        if type_after:
            time.sleep(type_after)
        if wrong_first:
            p.send(WRONG + "\n")
            assert p.expect("Sorry, try again", 15 + budget), f"[{name}] wrong password not refused\n{p.buf}"
            assert AUTHENTICATED not in p.buf, f"[{name}] a WRONG password was accepted\n{p.buf}"
            assert wait_prompts(p, 2, budget + 10), f"[{name}] no second prompt after a refusal\n{p.buf}"
        p.send(PASSWORD + "\n")
        status = p.wait(20 + budget)
        assert status == 0 and AUTHENTICATED in p.buf, f"[{name}] right password refused\n{p.buf}"
        total = time.monotonic() - t0
        REPORT.append({"case": name, "prompt_after_s": round(shown, 1), "total_s": round(total, 1)})
        return shown
    finally:
        reap(p)
