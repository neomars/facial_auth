def test_the_package_integrated_itself_into_the_system_pam_stack():
    stack = Path("/etc/pam.d/common-auth").read_text().splitlines()
    lines = [ln for ln in stack if ln and not ln.startswith("#")]
    assert "pam_facial_auth.so" in lines[0], "must come first"
    assert "conv_err=die" in lines[0] and "success=2" in lines[0]
    assert any("pam_unix.so" in ln and "try_first_pass" in ln for ln in lines), \
        "pam_unix must reuse a password typed while the camera was scanning"


def test_service_user_units_and_policies_are_installed_and_valid():
    out = subprocess.run(["getent", "passwd", "facial-auth"], capture_output=True, text=True).stdout
    assert out.split(":")[6].strip().endswith("nologin")
    assert "video" in subprocess.run(["id", "-nG", "facial-auth"], capture_output=True, text=True).stdout.split()
    if shutil.which("systemd-analyze"):
        v = subprocess.run(["systemd-analyze", "verify", "/usr/lib/systemd/system/facial-authd.service",
                            "/usr/lib/systemd/system/facial-authd.socket"], capture_output=True, text=True)
        assert v.returncode == 0 and "facial-authd" not in v.stderr.replace("facial-authd.s", ""), v.stderr
    import xml.dom.minidom as md
    pol = md.parse("/usr/share/polkit-1/actions/io.github.neomars.FacialAuth1.policy")
    ids = {a.getAttribute("id") for a in pol.getElementsByTagName("action")}
    assert ids == {"io.github.neomars.FacialAuth1.manage-faces", "io.github.neomars.FacialAuth1.configure",
                   "io.github.neomars.FacialAuth1.use-camera"}


def test_sudo_with_only_a_password_still_works_when_the_daemon_is_down(box):
    MARKER.parent.mkdir(parents=True, exist_ok=True)
    MARKER.touch()                                          # enrolled, but nobody listens
    SOCK.unlink(missing_ok=True)
    start = time.monotonic()
    p = Pty(sudo_cmd("sudo -k; sudo id -un"))
    assert p.expect("password for", 8) and "Looking for your face" not in p.buf
    p.send(PASSWORD + "\n")
    assert p.wait() == 0 and "root" in p.buf, p.buf
    assert time.monotonic() - start < 6


