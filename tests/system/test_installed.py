    assert p.expect(LR, 8), p.buf
    assert p.expect(NOT_COMPLETED, 10), p.buf
    assert time.monotonic() - t0 < 9, "the module waited for the whole scan budget"
    p.send(PASSWORD + "\n")
    assert p.wait() == 0 and "root" in p.buf, p.buf


